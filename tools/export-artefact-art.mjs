// Writes data/artefact-art.js — the list of artefacts that actually have a
// painted PNG, so artefacts.html can render an <img> for those and NOTHING for
// the rest. 38 of 180 are painted today; emitting a tag for the other 142 would
// be 142 console 404s, and this repo's bar is zero.
//
// WHY A COMMITTED MANIFEST. The site is plain static files with no build step,
// so the page cannot list a directory, and it must not learn a file is missing
// by watching a request fail. This runs by hand — like the two exporters beside
// it — and its output is committed. Re-run it whenever art lands.
//
// KEYED BY `name`, NOT by the slug. export-game-artefacts.mjs derives the game
// key as `a.key || slugify(a.name)`; duplicating that rule inside artefacts.html
// would be a second copy to drift. The page already has `a.name` in hand, so
// the join happens here, once, where both sides are visible.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const ART_DIR = "game/assets/artefacts";
const SITE_PATH = "game/assets/artefacts"; // relative to the site root, which
  // is the repo root: Pages serves the whole tree (root .nojekyll, no workflow),
  // so the game's art is already reachable and copying it would fork the file.

// data/artefacts.js is a plain script, not a module — same eval the CLAUDE.md
// structural check uses.
const ARTEFACTS = (0, eval)(
  readFileSync("data/artefacts.js", "utf8") + ";ARTEFACTS");

function slugify(name) {
  return String(name).toLowerCase()
    .normalize("NFKD").replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const painted = new Set(readdirSync(ART_DIR)
  .filter(f => f.endsWith(".png")).map(f => f.slice(0, -4)));

const out = {};
const used = new Set();
for (const a of ARTEFACTS) {
  const key = a.key || slugify(a.name);
  if (!painted.has(key)) continue;
  out[a.name] = `${SITE_PATH}/${key}.png`;
  used.add(key);
}

// A PNG no artefact claims is art that will never render — a rename on one side
// only. Loud, because the symptom is otherwise just a picture quietly missing.
const orphans = [...painted].filter(k => !used.has(k));
if (orphans.length) {
  throw new Error(`${orphans.length} PNG(s) match no artefact name: ${orphans.join(", ")}`);
}

writeFileSync("data/artefact-art.js",
  `/* GENERATED by tools/export-artefact-art.mjs — do not edit by hand.\n`
  + `   Artefact name -> painted PNG, for artefacts.html's expanded row. Only\n`
  + `   artefacts whose file exists on disk appear here; the page renders no\n`
  + `   image element at all for the rest, so a missing file cannot 404. */\n`
  + `const ARTEFACT_ART = ${JSON.stringify(out, null, 2)};\n\n`
  + `if (typeof module !== "undefined" && module.exports) module.exports = ARTEFACT_ART;\n`);

console.log(`wrote data/artefact-art.js (${Object.keys(out).length} of ${ARTEFACTS.length} artefacts have art)`);
